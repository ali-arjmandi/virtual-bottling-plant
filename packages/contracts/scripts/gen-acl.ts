// Writes infra/broker/acl.conf (EMQX file authorization) from the `acl` table in topics.yaml.
// Run by `pnpm gen:contracts` after gen.ts; CI fails if the committed file differs.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { topicsDoc } from '../src/contract-types.js';
import { aclTopic } from '../src/uns-topics.js';

const target = resolve(import.meta.dirname, '../../../infra/broker/acl.conf');

function rules(user: string, action: 'publish' | 'subscribe', entries: readonly string[]): string[] {
  return entries.map((e) => `{allow, {user, "${user}"}, ${action}, ["${aclTopic(e)}"]}.`);
}

const lines = [
  '%% GENERATED by packages/contracts/scripts/gen-acl.ts from contracts/uns/topics.yaml.',
  '%% Do not edit. One user per client (UNS-02); anything not allowed here is denied.',
  '',
  ...Object.entries(topicsDoc.acl).flatMap(([user, acl]) => [
    `%% ${user}`,
    ...rules(user, 'publish', acl.publish),
    ...rules(user, 'subscribe', acl.subscribe),
    '',
  ]),
  '{deny, all}.',
  '',
];

writeFileSync(target, lines.join('\n'));
console.log('wrote infra/broker/acl.conf');
