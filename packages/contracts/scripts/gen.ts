// Generates src/generated/ from /contracts (contracts.md §6). Run: pnpm gen:contracts
// CI runs it and fails if the output differs from what is committed.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { parse } from 'yaml';

const root = resolve(import.meta.dirname, '../../..');
const contracts = join(root, 'contracts');
const out = resolve(import.meta.dirname, '../src/generated');
const banner = '// GENERATED by packages/contracts/scripts/gen.ts from /contracts. Do not edit.\n';

type Schema = {
  title?: string;
  allOf?: { $ref: string }[];
  properties?: Record<string, unknown>;
  required?: string[];
  [key: string]: unknown;
};

function loadSchemas(): Record<string, Schema> {
  const dir = join(contracts, 'schemas');
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  return Object.fromEntries(files.map((f) => [f, JSON.parse(readFileSync(join(dir, f), 'utf8'))]));
}

/** Inlines the envelope so each message type reads as one flat interface. */
function flatten(schema: Schema, all: Record<string, Schema>): Schema {
  const refs = (schema.allOf ?? []).map((a) => all[a.$ref]);
  const own = Object.entries(schema.properties ?? {}).filter(([, v]) => v !== true);
  const properties = Object.assign({}, ...refs.map((r) => r?.properties ?? {}), Object.fromEntries(own));
  const required = [...refs.flatMap((r) => r?.required ?? []), ...(schema.required ?? [])];
  const { allOf: _allOf, $id: _id, ...rest } = schema;
  return { ...rest, properties, required };
}

async function genTypes(schemas: Record<string, Schema>): Promise<string> {
  const parts: string[] = [];
  for (const schema of Object.values(schemas)) {
    parts.push(await compile(flatten(schema, schemas) as JSONSchema, String(schema.title), {
      bannerComment: '', additionalProperties: false, format: true,
    }));
  }
  return banner + parts.join('\n');
}

function genConst(name: string, value: unknown): string {
  return `${banner}export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
}

function write(file: string, content: string): void {
  writeFileSync(join(out, file), content);
  console.log(`wrote src/generated/${file}`);
}

async function main(): Promise<void> {
  mkdirSync(out, { recursive: true });
  const schemas = loadSchemas();
  write('schema-types.ts', await genTypes(schemas));
  write('schemas.ts', genConst('schemas', schemas));
  write('plc-io.ts', genConst('plcIo', parse(readFileSync(join(contracts, 'modbus/plc-io.yaml'), 'utf8'))));
  write('topics.ts', genConst('topics', parse(readFileSync(join(contracts, 'uns/topics.yaml'), 'utf8'))));
}

await main();
