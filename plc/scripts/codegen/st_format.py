"""Text building blocks for generated Structured Text."""

from __future__ import annotations

from collections.abc import Iterable


def banner(source: str, purpose: str) -> str:
    return (f"(* GENERATED by plc/scripts/gen_plc_io.py from {source}. Do not edit by hand. *)\n"
            f"(* {purpose} *)\n")


def var_block(kind: str, decls: Iterable[str], indent: str = "  ") -> str:
    lines = [f"{indent}{kind}"] + [f"{indent}  {d}" for d in decls] + [f"{indent}END_VAR"]
    return "\n".join(lines) + "\n"


def program(name: str, header: str, externals: list[str], located: list[str],
            body: list[str]) -> str:
    """One PROGRAM. Located variables get their own VAR block (matiec rule, ADR 0005)."""
    out = header + f"PROGRAM {name}\n"
    if externals:
        out += var_block("VAR_EXTERNAL", externals)
    if located:
        out += var_block("VAR", located)
    out += "".join(f"  {line}\n" for line in body)
    return out + "END_PROGRAM\n"


def num(value: float) -> str:
    """REAL literal without trailing noise: 10 → 10.0, 0.5 → 0.5."""
    return f"{value:.1f}" if float(value).is_integer() else repr(float(value))


def to_int_word(expr: str, st_type: str, scale: float = 1.0) -> str:
    """PLC value → signed 16-bit status word."""
    if st_type == "BOOL":
        return f"BOOL_TO_INT({expr})"
    if st_type.startswith("E_"):
        return f"{st_type[2:]}ToInt({expr})"
    if st_type == "REAL":
        scaled = expr if scale == 1.0 else f"{expr} * {num(scale)}"
        return f"REAL_TO_INT({scaled})"
    if st_type == "UINT":
        return f"UINT_TO_INT({expr})"
    if st_type == "UDINT":
        return f"UDINT_TO_INT({expr})"
    return expr


def from_int_word(raw: str, st_type: str, scale: float = 1.0) -> str:
    """Signed 16-bit command/recipe word → PLC value."""
    if st_type == "BOOL":
        return f"{raw} <> 0"
    if st_type.startswith("E_"):
        return f"IntTo{st_type[2:]}({raw})"
    if st_type == "REAL":
        return f"INT_TO_REAL({raw})" + ("" if scale == 1.0 else f" / {num(scale)}")
    return raw


def word_type(entry: dict) -> str:
    """PLC type of a command or recipe word from plc-io.yaml."""
    if entry.get("type") == "bool":
        return "BOOL"
    if "enum" in entry:
        return f"E_{entry['enum']}"
    return "REAL" if float(entry.get("scale", 1)) != 1.0 else "INT"
